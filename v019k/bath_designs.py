def retarded_A(z,h):
    A=np.sqrt(z*(z+3.0*h)+0j)
    if np.isscalar(A):
        return -A if A.real < 0 else A
    A=np.asarray(A,dtype=complex)
    flip=A.real<0
    A[flip]*=-1
    return A


def exact_kernel(A):
    return A/(1.0+A)


def finite_kernel(A,nodes,weights):
    A=np.asarray(A,dtype=complex)
    return np.sum(weights*A[...,None]**2/(nodes**2+A[...,None]**2),axis=-1)


def log_quadrature(N,T=10.0):
    t=np.linspace(-T,T,N)
    dt=t[1]-t[0]
    r=np.exp(t)
    w=(2.0/np.pi)*r/(1.0+r*r)*dt
    w[0]*=0.5
    w[-1]*=0.5
    return r,w
